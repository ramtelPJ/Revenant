// Everything `npm run setup-check` decides. Relative imports end in .ts because the script runs under plain Node.
import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { checkOllama as realCheckOllama, type OllamaHealth } from "./ai/ollama-health.ts";
import { parseEnv } from "./env.ts";
import { START_OLLAMA_FIX, pullImageFix, pullModelFix } from "./fixes.ts";
import { IMAGE_NAME_PATTERN } from "./sandbox/checks.ts";
import { resolveDockerBin } from "./sandbox/docker.ts";
import { checkDocker as realCheckDocker, type DockerHealth } from "./sandbox/docker-health.ts";

export type CheckResult = {
  id: string;
  label: string;
  status: "ok" | "fail" | "warn";
  /** A failed required check makes setup incomplete (exit code 1). Warnings never do. */
  required: boolean;
  detail: string;
  fix?: string;
};

export type SetupDeps = {
  env: Record<string, string | undefined>;
  nodeVersion: string; // like "v26.10.0"
  platform: NodeJS.Platform;
  cwd: string;
  checkOllama: (url: string, model: string) => Promise<OllamaHealth>;
  checkDocker: (image: string) => Promise<DockerHealth>;
  dockerBin: () => Promise<string | undefined>;
};

const DEFAULT_OLLAMA_URL = "http://127.0.0.1:11434";
const DEFAULT_IMAGE = "node:lts-slim";
// the secrets are generated by the launcher on every start, so they are not part of "is setup complete"
const PLACEHOLDER = "0".repeat(64);

/** Node 22.18 is the first 22.x that runs the project's TypeScript scripts without a flag. */
export function nodeVersionOk(version: string): boolean {
  const match = /^v?(\d+)\.(\d+)\./.exec(version);
  if (!match) return false;
  const [major, minor] = [Number(match[1]), Number(match[2])];
  return major > 22 || (major === 22 && minor >= 18);
}

export async function runSetupChecks(overrides: Partial<SetupDeps> = {}): Promise<CheckResult[]> {
  const deps: SetupDeps = {
    env: process.env,
    nodeVersion: process.version,
    platform: process.platform,
    cwd: process.cwd(),
    checkOllama: realCheckOllama,
    checkDocker: realCheckDocker,
    dockerBin: () => resolveDockerBin(),
    ...overrides,
  };
  const results: CheckResult[] = [];

  // 1. Node
  const nodeOk = nodeVersionOk(deps.nodeVersion);
  results.push({
    id: "node",
    label: "Node.js",
    status: nodeOk ? "ok" : "fail",
    required: true,
    detail: nodeOk ? deps.nodeVersion : `${deps.nodeVersion} is too old; Node 22.18 or newer is needed`,
    fix: nodeOk ? undefined : "Install the current Node.js LTS from https://nodejs.org",
  });

  // 2. configuration. Only validated values are used afterwards, so a bad OLLAMA_URL is never contacted.
  let ollamaUrl = DEFAULT_OLLAMA_URL;
  let model: string | undefined;
  let configOk = true;
  let image = DEFAULT_IMAGE;
  try {
    const config = parseEnv({ ...deps.env, REVENANT_LAUNCH_TOKEN: PLACEHOLDER, REVENANT_SESSION_SECRET: PLACEHOLDER });
    ollamaUrl = config.OLLAMA_URL;
    model = config.OLLAMA_MODEL;
    image = config.SANDBOX_IMAGE;
    results.push({ id: "config", label: "Configuration", status: "ok", required: true, detail: `model ${model}, image ${image}` });
  } catch (error) {
    configOk = false;
    results.push({
      id: "config",
      label: "Configuration",
      status: "fail",
      required: true,
      detail: (error instanceof Error ? error.message : "invalid").replace(/^Invalid environment:\n/, "").replace(/\n\s*/g, "; ").trim(),
      fix: "Correct the setting(s) named above in .env.local (see .env.example). The secrets are created for you at launch.",
    });
    // a valid model/image may still be present even if something else is wrong
    model = deps.env.OLLAMA_MODEL || undefined;
    if (deps.env.SANDBOX_IMAGE && IMAGE_NAME_PATTERN.test(deps.env.SANDBOX_IMAGE)) image = deps.env.SANDBOX_IMAGE;
  }

  // 3. the local model
  if (!model) {
    results.push({ id: "ollama", label: "Local AI (Ollama)", status: "fail", required: true, detail: "no model is configured, so it cannot be checked", fix: "Set OLLAMA_MODEL in .env.local" });
  } else {
    const ollama = await deps.checkOllama(ollamaUrl, model);
    // when the configuration is invalid, the configured address is never trusted or contacted
    const where = configOk ? ollamaUrl : `${ollamaUrl} (the default address, because the configuration is invalid)`;
    if (!ollama.reachable) {
      results.push({ id: "ollama", label: "Local AI (Ollama)", status: "fail", required: true, detail: `not reachable at ${where}`, fix: START_OLLAMA_FIX });
    } else if (!ollama.modelInstalled) {
      results.push({ id: "ollama", label: "Local AI (Ollama)", status: "fail", required: true, detail: `running at ${where}, but model ${model} is not installed`, fix: pullModelFix(model) });
    } else {
      results.push({ id: "ollama", label: "Local AI (Ollama)", status: "ok", required: true, detail: `running at ${where}, model ${model} installed` });
    }
  }

  // 4. the sandbox
  const docker = await deps.checkDocker(image);
  if (!docker.available) {
    results.push({
      id: "docker",
      label: "Docker",
      status: "fail",
      required: true,
      detail: "not found, or the engine is not running",
      fix:
        deps.platform === "darwin"
          ? "Install Docker Desktop (https://docs.docker.com/desktop/) and start it; if `docker` is not found, add /Applications/Docker.app/Contents/Resources/bin to your PATH"
          : "Install Docker (https://docs.docker.com/get-docker/) and start the engine",
    });
  } else {
    const bin = await deps.dockerBin();
    const offPath = bin !== undefined && bin !== "docker";
    results.push({
      id: "docker",
      label: "Docker",
      status: offPath ? "warn" : "ok",
      required: true,
      detail: offPath ? `engine running, but \`docker\` is not on your PATH (found ${bin})` : "engine running",
      fix: offPath ? `Add ${path.dirname(bin)} to your PATH so other tools can find it` : undefined,
    });
    results.push(
      docker.imagePresent
        ? { id: "image", label: "Sandbox image", status: "ok", required: true, detail: `${image} is installed` }
        : { id: "image", label: "Sandbox image", status: "fail", required: true, detail: `${image} is not installed`, fix: pullImageFix(image) },
    );
  }

  // 5. recommended, not required: the demo samples and the production build
  results.push(checkSamples(deps.cwd));
  const built = existsSync(path.join(deps.cwd, ".next", "BUILD_ID"));
  results.push({
    id: "build",
    label: "Production build",
    status: built ? "ok" : "warn",
    required: false,
    detail: built ? "found" : "not built yet; `npm run revenant` needs it",
    fix: built ? undefined : "Run `npm run build`",
  });

  return results;
}

function checkSamples(cwd: string): CheckResult {
  const base = { id: "samples", label: "Demo samples", required: false } as const;
  const dir = path.join(cwd, "samples");
  let names: string[];
  try {
    names = readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort();
  } catch {
    return { ...base, status: "ok", detail: "no samples folder (nothing to prepare)" };
  }

  const missing: string[] = [];
  let checked = 0;
  for (const name of names) {
    const manifest = path.join(dir, name, "package.json");
    if (!existsSync(manifest)) continue;
    let dependencies: string[] = [];
    try {
      const parsed = JSON.parse(readFileSync(manifest, "utf8")) as { dependencies?: object; devDependencies?: object };
      dependencies = [...Object.keys(parsed.dependencies ?? {}), ...Object.keys(parsed.devDependencies ?? {})];
    } catch {
      /* a broken manifest is reported by the sample tests, not here */
    }
    checked++;
    if (dependencies.some((dep) => !existsSync(path.join(dir, name, "node_modules", dep)))) missing.push(name);
  }
  if (missing.length === 0) return { ...base, status: "ok", detail: `${checked} sample${checked === 1 ? "" : "s"} ready` };
  return { ...base, status: "warn", detail: `dependencies not installed for: ${missing.join(", ")}`, fix: "Run `npm run prepare-samples`" };
}

const MARK = { ok: "✓", fail: "✗", warn: "!" } as const;

export function formatReport(results: CheckResult[]): { text: string; ok: boolean } {
  const lines: string[] = [];
  for (const r of results) {
    lines.push(`${MARK[r.status]} ${r.label}: ${r.detail}${r.required ? "" : "  (optional)"}`);
    if (r.fix && r.status !== "ok") lines.push(`    fix: ${r.fix}`);
  }
  const failed = results.filter((r) => r.status === "fail" && r.required);
  const warned = results.filter((r) => r.status === "warn");
  lines.push("");
  lines.push(
    failed.length > 0
      ? `Setup is not complete: ${failed.length} required item${failed.length === 1 ? "" : "s"} missing.`
      : warned.length > 0
        ? `Setup is complete. ${warned.length} optional item${warned.length === 1 ? "" : "s"} could be improved.`
        : "Setup is complete.",
  );
  return { text: lines.join("\n"), ok: failed.length === 0 };
}
